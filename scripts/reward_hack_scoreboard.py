#!/usr/bin/env python3
"""Score every saved attack: which environments got hacked, by what, and how often.

Reads exploits/*_hack_candidates.jsonl and prints a scoreboard. Use --markdown to
write docs/SCOREBOARD.md, or --gate to exit non-zero when any environment still
has a reward-hack candidate (handy as a regression check after hardening a verifier).
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXPLOITS = ROOT / "exploits"
SCOREBOARD_MD = ROOT / "docs" / "SCOREBOARD.md"
SUFFIX = "_hack_candidates.jsonl"


def read_jsonl(path: Path):
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def kind_of(row):
    return row.get("candidate_kind") or row.get("schema_type") or "(unlabelled)"


def score(path: Path):
    rows = read_jsonl(path)
    hacks = [r for r in rows if r.get("is_reward_hack_candidate")]
    tried = Counter(kind_of(r) for r in rows)
    landed = Counter(kind_of(r) for r in hacks)
    reasons = Counter(reason for r in hacks for reason in r.get("violation_reasons", []))
    return {
        "env": path.name[: -len(SUFFIX)],
        "candidates": len(rows),
        "hacks": len(hacks),
        "kinds": {k: (landed[k], n) for k, n in tried.most_common()},
        "top_reason": reasons.most_common(1)[0][0] if reasons else "",
    }


def verdict(s):
    if s["hacks"] == 0:
        return "HELD"
    if s["hacks"] == s["candidates"]:
        return "BROKEN"
    return "LEAKY"


def bar(hacks, total, width=20):
    filled = round(width * hacks / total) if total else 0
    return "#" * filled + "." * (width - filled)


def clip(s, n):
    s = str(s).replace("\n", " ")
    return s[:n] + ("..." if len(s) > n else "")


def render_text(scores):
    lines = []
    for s in scores:
        rate = s["hacks"] / s["candidates"] if s["candidates"] else 0.0
        lines.append(f"\n{s['env']:<20} [{bar(s['hacks'], s['candidates'])}] "
                     f"{s['hacks']}/{s['candidates']} ({rate:.0%})  {verdict(s)}")
        for kind, (landed, tried) in s["kinds"].items():
            mark = "x" if landed else " "
            lines.append(f"  [{mark}] {kind:<45} {landed}/{tried}")
        if s["top_reason"]:
            lines.append(f"  why: {clip(s['top_reason'], 100)}")
    total_h = sum(s["hacks"] for s in scores)
    total_c = sum(s["candidates"] for s in scores)
    lines.append(f"\nTOTAL {total_h}/{total_c} candidates are reward hacks across {len(scores)} environments.")
    return "\n".join(lines)


def render_markdown(scores):
    out = [
        "# Reward-Hack Scoreboard",
        "",
        "Generated by `python3 scripts/reward_hack_scoreboard.py --markdown`. Do not edit by hand.",
        "",
        "| Environment | Hacks | Rate | Verdict | Most common violation |",
        "|---|---:|---:|---|---|",
    ]
    for s in scores:
        rate = s["hacks"] / s["candidates"] if s["candidates"] else 0.0
        out.append(f"| `{s['env']}` | {s['hacks']}/{s['candidates']} | {rate:.0%} | "
                   f"{verdict(s)} | {clip(s['top_reason'], 120) or '-'} |")
    out += ["", "## Attack kinds", ""]
    for s in scores:
        out.append(f"### `{s['env']}`")
        out.append("")
        for kind, (landed, tried) in s["kinds"].items():
            out.append(f"- {'**landed**' if landed else 'missed'} `{kind}`: {landed}/{tried}")
        out.append("")
    out += [
        "Verdicts: **BROKEN** = every candidate got rewarded, **LEAKY** = some did, "
        "**HELD** = none did.",
        "",
    ]
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--markdown", action="store_true", help=f"write {SCOREBOARD_MD.relative_to(ROOT)}")
    parser.add_argument("--gate", action="store_true", help="exit 1 if any reward hack is present")
    args = parser.parse_args()

    paths = sorted(EXPLOITS.glob("*" + SUFFIX))
    if not paths:
        print("No evidence found. Run one of the scripts/generate_*_hacks.py generators first.")
        return 0
    scores = sorted((score(p) for p in paths), key=lambda s: (-s["hacks"], s["env"]))

    print(render_text(scores))
    if args.markdown:
        SCOREBOARD_MD.write_text(render_markdown(scores))
        print(f"\nWrote {SCOREBOARD_MD.relative_to(ROOT)}")
    if args.gate and any(s["hacks"] for s in scores):
        print("\nGATE FAILED: at least one verifier still rewards a hack.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
